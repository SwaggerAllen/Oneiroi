import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('./src/tokens.json', import.meta.url), 'utf8'));
const lines = [];
const color = (theme) => t.color.tokens.map((c) => `  --${c.name}: ${c.value[theme]};`).join('\n');
const shadow = (theme) => t.shadow.tokens.map((s) => `  --${s.name}: ${s.value[theme]};`).join('\n');
const flat = (group) => group.tokens.map((x) => `  --${x.name}: ${x.value};`).join('\n');
lines.push('/* Generated from src/tokens.json by scripts-tokens-to-css.mjs; do not edit. */');
lines.push(':root {');
lines.push(color('light'));
lines.push(shadow('light'));
lines.push(flat(t.spacing));
lines.push(flat(t.radius));
lines.push(flat(t.size));
lines.push(`  --font-sans: ${t.type.families.sans};`);
lines.push(`  --font-serif: ${t.type.families.serif};`);
lines.push(`  --font-mono: ${t.type.families.mono};`);
lines.push('}');
lines.push(':root[data-theme="dark"] {');
lines.push(color('dark'));
lines.push(shadow('dark'));
lines.push('}');
lines.push('@media (prefers-color-scheme: dark) {');
lines.push('  :root:not([data-theme="light"]) {');
lines.push(color('dark').replace(/^/gm, '  '));
lines.push(shadow('dark').replace(/^/gm, '  '));
lines.push('  }');
lines.push('}');
lines.push('body { margin: 0; background: var(--surface); color: var(--ink); font-family: var(--font-sans); }');
writeFileSync(new URL('./src/theme.css', import.meta.url), lines.join('\n') + '\n');
